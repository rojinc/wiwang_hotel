#!/usr/bin/env python3
"""Generate the qb-doorlock config for the 380 Wiwang Hotel room doors.

Runs wiwang_apartments/config.lua + shared/rooms.lua in a Lua 5.4 VM (pip install lupa) so the
coordinates are exactly what the resource itself uses. Output: wiwang_apartments/doorlock/qb-doorlock/wiwang_hotel.lua
"""
import os, sys
from lupa import lua54

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'wiwang_apartments')
L = lua54.LuaRuntime()
L.execute(r'''
local function joaat_(s) local h = 0; for i = 1, #s do local c = s:sub(i,i):lower():byte(); h = (h + c) & 0xffffffff; h = (h + (h << 10)) & 0xffffffff; h = h ~ (h >> 6) end
  h = (h + (h << 3)) & 0xffffffff; h = h ~ (h >> 11); h = (h + (h << 15)) & 0xffffffff; return h end
joaat = joaat_
local mt = {}; mt.__index = mt
mt.__add = function(a, b) return vec3(a.x + b.x, a.y + b.y, a.z + b.z) end
mt.__sub = function(a, b) return vec3(a.x - b.x, a.y - b.y, a.z - b.z) end
mt.__div = function(a, n) return vec3(a.x / n, a.y / n, a.z / n) end
function vec3(x, y, z) return setmetatable({x = x, y = y, z = z}, mt) end
function vec4(x, y, z, w) return setmetatable({x = x, y = y, z = z, w = w}, mt) end
vector3 = vec3; vector4 = vec4
''')
for f in ('config.lua', 'shared/rooms.lua'):
    L.execute(open(os.path.join(ROOT, f)).read())
rooms = L.globals().Rooms
lines = [
    "-- GENERATED by tools/gen_qb_doorlock.py - Wiwang Hotel room doors for qb-doorlock.",
    "-- Copy this file into qb-doorlock/configs/ (its manifest loads configs/*.lua).",
    "-- Door ids equal the wiwang_apartments room ids. Nobody is authorised here on purpose: wiwang_apartments",
    "-- flips the state itself (owner / keys / knock) with qb-doorlock:server:updateState. hideLabel keeps",
    "-- qb-doorlock's own text off the doors; wiwang_apartments shows its own [E] prompt.",
    "",
]
count = 0
for floor in range(1, int(rooms.Floors) + 1):
    for number in range(1, len(rooms.Template) + 1):
        r = rooms.Get(floor, number)
        d = r.door
        lines.append(
            "Config.DoorList['%s'] = { objName = 'floky_wiwang_wood_door_01', objYaw = %.1f, objCoords = vec3(%.3f, %.3f, %.3f), "
            "textCoords = vec3(%.3f, %.3f, %.3f), locked = false, pickable = false, cantUnlock = true, hideLabel = true, "
            "distance = 1.5, doorLabel = '%s', doorType = 'door', doorRate = 1.0, fixText = false }"
            % (r.id, r.doorHeading, d.x, d.y, d.z, d.x, d.y, d.z, r.label))
        count += 1
out = os.path.join(ROOT, 'doorlock', 'qb-doorlock', 'wiwang_hotel.lua')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote %s (%d doors)' % (os.path.relpath(out), count))
